export class MockLearningRepository implements LearningRepository {
  private resources: LearningResource[] = [...MOCK_LEARNING_RESOURCES];
  private bookmarks = new Set<string>(); // Format: `${userId}:${resourceId}`

  async getResources(options?: GetLearningResourcesOptions): Promise<LearningResource[]> {
    let result = [...this.resources];

    if (options?.category) {
      result = result.filter((r) => r.category === options.category);
    }

    if (options?.content_type) {
      result = result.filter((r) => r.content_type === options.content_type);
    }

    if (options?.crop) {
      result = result.filter(
        (r) =>
          r.crop?.toLowerCase().includes(options.crop!.toLowerCase()) ||
          r.crop === "सर्व पिके"
      );
    }

    if (options?.difficulty) {
      result = result.filter((r) => r.difficulty === options.difficulty);
    }

    if (options?.search) {
      const q = options.search.toLowerCase();
      result = result.filter(
        (r) =>
          r.title.toLowerCase().includes(q) ||
          r.summary.toLowerCase().includes(q) ||
          r.tags?.some((t) => t.toLowerCase().includes(q))
      );
    }

    if (options?.userId && options?.bookmarkedOnly) {
      result = result.filter((r) => this.bookmarks.has(`${options.userId}:${r.id}`));
    }

    if (options?.userId) {
      result = result.map((r) => ({
        ...r,
        is_bookmarked: this.bookmarks.has(`${options.userId}:${r.id}`),
      }));
    }

    return result;
  }

  async getResourceById(id: string, userId?: string): Promise<LearningResource | null> {
    const res = this.resources.find((r) => r.id === id || r.slug === id);
    if (!res) return null;
    return {
      ...res,
      is_bookmarked: userId ? this.bookmarks.has(`${userId}:${res.id}`) : false,
    };
  }

  async toggleBookmark(resourceId: string, userId: string): Promise<boolean> {
    const key = `${userId}:${resourceId}`;
    if (this.bookmarks.has(key)) {
      this.bookmarks.delete(key);
      return false;
    } else {
      this.bookmarks.add(key);
      return true;
    }
  }

  async getRecentOrPopular(limit: number = 4): Promise<LearningResource[]> {
    return [...this.resources]
      .sort((a, b) => b.view_count - a.view_count)
      .slice(0, limit);
  }
}
